// Flutter aliases whose glyph lives under another name.
const ALIAS = {
  copy: "content_copy",
  info_outline: ["outlined", "info"],
  lock_outline: ["outlined", "lock"],
};

function resolve(name) {
  if (CUSTOM[name]) return { markup: CUSTOM[name] };
  let family = "filled";
  let base = name;
  for (const [suffix, fam] of [["_outlined", "outlined"], ["_rounded", "round"], ["_sharp", "sharp"]]) {
    if (name.endsWith(suffix)) { family = fam; base = name.slice(0, -suffix.length); break; }
  }
  const alias = ALIAS[base];
  if (Array.isArray(alias)) [family, base] = alias;
  else if (alias) base = alias;
  const file = path.join(root, family, `${base}.svg`);
  if (!fs.existsSync(file)) return null;
  const svg = fs.readFileSync(file, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  return { markup: inner };
}

// Parse the (machine generated) SVG body into [tag, attrs] tuples so React can
// render it with createElement instead of dangerouslySetInnerHTML.
function parse(markup) {
  const nodes = [];
  const re = /<(path|circle|rect|polygon|ellipse|g)\b([^>]*?)\/?>/g;
  let m;
  while ((m = re.exec(markup))) {
    const [, tag, rawAttrs] = m;
    if (tag === "g") continue;
    const attrs = {};
    for (const a of rawAttrs.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    if (attrs.fill === "none") continue;
    const out = {};
    for (const [k, v] of Object.entries(attrs)) {
      if (["d", "cx", "cy", "r", "x", "y", "width", "height", "points", "rx", "ry", "opacity", "transform"].includes(k)) out[k] = v;
      else if (k === "fill-opacity") out.fillOpacity = v;
      else if (k === "fill-rule") out.fillRule = v;
      else if (k === "clip-rule") out.clipRule = v;
    }
    nodes.push([tag, out]);
  }
  return nodes;
}

const all = [...new Set([...names, ...extra])].sort();
const entries = [];
const missing = [];
for (const name of all) {
  const r = resolve(name);
  if (!r) { missing.push(name); continue; }
  const nodes = parse(r.markup);
  if (!nodes.length) { missing.push(name + " (empty)"); continue; }
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`);
}
if (missing.length) { console.error("MISSING:", missing.join(", ")); process.exit(1); }

